`timescale 1ns/1ps

module data_memory (

    //============================================================
    // Data Inputs
    //============================================================

    input  wire [31:0] alu_result,
    input  wire [31:0] write_data,

    //============================================================
    // Control Inputs
    //============================================================

    input  wire        mem_read,
    input  wire        mem_write,

    input  wire        clk,

    //============================================================
    // Data Output
    //============================================================

    output reg [31:0]  dmem_data

);

    //============================================================
    // Data Memory
    //============================================================

    reg [31:0] memory [0:1023];

    //------------------------------------------------------------
    // Synchronous Write
    //------------------------------------------------------------

    always @(posedge clk) begin

        if (mem_write)
            memory[alu_result[11:2]] <= write_data;

    end

    //------------------------------------------------------------
    // Combinational Read
    //------------------------------------------------------------

    always @(*) begin

        if (mem_read)
            dmem_data = memory[alu_result[11:2]];
        else
            dmem_data = 32'b0;

    end

endmodule